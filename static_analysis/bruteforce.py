expected = [
    0x80, 0xE4, 0x08, 0x18, 0x4A, 0x58, 0xB8, 0xE4,
    0xAC, 0x34, 0x58, 0xE4, 0x7E, 0xBC, 0x9E, 0x8C,
    0x7E, 0xD0, 0xC0, 0x7C, 0xAC, 0xF4, 0x7E, 0x28,
    0x9E, 0x04, 0x7E, 0xBC, 0x9E, 0x8C, 0x7E, 0x5C,
    0x14, 0x4C, 0x7E, 0x5C, 0x7E, 0x6C, 0x02, 0x14,
    0xB8, 0x4C, 0x14, 0xA4, 0x9E, 0x08, 0x7E, 0xE4,
    0xF4, 0x08, 0x6A, 0x14, 0xA6, 0x5C, 0xB8, 0x7C,
    0x9E, 0x28, 0x3E, 0xAC,
]


def transform(character: int, position: int) -> int:
    if position % 2 == 0:
        return ((character * -46) ^ -368) & 0xFF

    return ((character * 316) ^ 2528) & 0xFF


for position, target in enumerate(expected):
    candidates = []

    for character in range(32, 127):
        if transform(character, position) == target:
            candidates.append(chr(character))

    print(f"{position:02}: {candidates}")
